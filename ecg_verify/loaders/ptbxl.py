"""PTB-XL (PhysioNet, v1.0.3) adapter.

Structure (inspected from the downloaded dataset): ``ptbxl_database.csv`` with one row per ECG,
``scp_codes`` as a Python-literal dict ``{SCP code: likelihood}`` (likelihood in {0, 15, 35, 50,
80, 100}; 0 means "not specified", used for all rhythm/form statements), ``filename_hr`` pointing
to 500 Hz WFDB records (12 leads I..V6, 10 s, mV), ``strat_fold`` 1-10 (patient-wise), and
``heart_axis`` as a separate column.
"""

from __future__ import annotations

import ast
import math
import os

import pandas as pd
import wfdb

from .base import DatasetAdapter, RawSignal, RecordRef


class PTBXLAdapter(DatasetAdapter):
    name = "ptbxl"
    default_mapping = "ptbxl_scp"
    # PTB-XL statements were assigned by cardiologists (or auto-generated and then reviewed);
    # absence of a statement is *not* a verified negative.
    default_absence_semantics = "unknown"
    overlap_note = (
        "PTB-XL (Physikalisch-Technische Bundesanstalt, Berlin; Schiller devices, 1989-1996) is not "
        "part of ECGFounder's pretraining data (Harvard-Emory ECG Database, MGH + Emory). The "
        "official repository uses PTB-XL as an external validation set for the 150-class head "
        "(ptbxl_eval.py, csv/ptbxl_label.csv) and the paper uses it for downstream experiments. "
        "Released 150-class weights are therefore not expected to have been trained on these "
        "labels, but thresholds published by the authors were tuned on PTB-XL and are not reused."
    )
    stratify_by = ("validated_by_human", "initial_autogenerated_report", "second_opinion",
                   "device", "strat_fold")

    @classmethod
    def detect(cls, root: str) -> bool:
        return os.path.isfile(os.path.join(root, "ptbxl_database.csv"))

    def records(self) -> list[RecordRef]:
        db = pd.read_csv(os.path.join(self.root, "ptbxl_database.csv"))
        use_lr = bool(self.options.get("use_low_rate", False))
        min_lik = float(self.options.get("min_label_likelihood", 0))
        include_axis = bool(self.options.get("include_heart_axis", True))
        refs = []
        for row in db.itertuples(index=False):
            codes = ast.literal_eval(row.scp_codes)
            labels, dropped = {}, {}
            for code, lik in codes.items():
                lik = float(lik)
                (dropped if 0 < lik < min_lik else labels)[code] = lik
            axis = row.heart_axis
            if include_axis and isinstance(axis, str) and axis.strip():
                labels[f"AXIS_{axis.strip()}"] = 0.0
            meta = {
                "validated_by_human": bool(row.validated_by_human),
                "initial_autogenerated_report": bool(row.initial_autogenerated_report),
                "second_opinion": bool(row.second_opinion),
                "device": row.device,
                "site": None if _nan(row.site) else row.site,
                "strat_fold": int(row.strat_fold),
                "report": row.report,
                "dropped_low_likelihood": dropped or None,
            }
            refs.append(RecordRef(
                record_id=str(int(row.ecg_id)),
                labels=labels,
                source=row.filename_lr if use_lr else row.filename_hr,
                patient_id=str(int(row.patient_id)),
                fold_hint=int(row.strat_fold),
                metadata=meta,
            ))
        return refs

    def load(self, ref: RecordRef) -> RawSignal:
        rec = wfdb.rdrecord(os.path.join(self.root, ref.source))
        return RawSignal(rec.p_signal.T, float(rec.fs), list(rec.sig_name))


def _nan(x) -> bool:
    return x is None or (isinstance(x, float) and math.isnan(x))
