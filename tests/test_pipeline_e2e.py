"""End-to-end tests on small synthetic datasets written in the real on-disk formats.

The model is a randomly initialised ECGFounder architecture saved in the official checkpoint
format: it exercises loading, batching, caching and reporting, NOT model quality.
"""

import hashlib
import json
from pathlib import Path

import numpy as np
import pandas as pd
import pytest
import torch
import wfdb

from ecg_verify.ecgfounder import build_model, load_pretrained
from verify_ecg_labels import main

LEADS = ["I", "II", "III", "AVR", "AVL", "AVF", "V1", "V2", "V3", "V4", "V5", "V6"]


@pytest.fixture(scope="module")
def checkpoint(tmp_path_factory):
    torch.manual_seed(0)
    p = tmp_path_factory.mktemp("ckpt") / "random_12lead.pth"
    torch.save({"state_dict": build_model(12).state_dict()}, p)
    return p


def _signal(fs, seconds, seed):
    rng = np.random.default_rng(seed)
    t = np.arange(int(fs * seconds)) / fs
    return (np.sin(2 * np.pi * 1.1 * t)[:, None] * rng.uniform(0.3, 1.2, 12)
            + 0.05 * rng.standard_normal((len(t), 12)))


def make_ptbxl(root: Path, n=10):
    rows = []
    codes = [{"NORM": 100.0, "SR": 0.0}, {"AFIB": 0.0, "LVH": 50.0}, {"IMI": 80.0, "SR": 0.0},
             {"CLBBB": 100.0, "SR": 0.0, "ISC_": 50.0}, {"NDT": 100.0, "SBRAD": 0.0}]
    for i in range(1, n + 1):
        rel = f"records500/00000/{i:05d}_hr"
        (root / rel).parent.mkdir(parents=True, exist_ok=True)
        wfdb.wrsamp(f"{i:05d}_hr", fs=500, units=["mV"] * 12, sig_name=LEADS,
                    p_signal=_signal(500, 10, i), fmt=["16"] * 12, write_dir=str((root / rel).parent))
        rows.append({"ecg_id": i, "patient_id": 100 + i // 2, "scp_codes": str(codes[i % 5]),
                     "heart_axis": "LAD" if i % 3 == 0 else np.nan, "validated_by_human": i % 2 == 0,
                     "initial_autogenerated_report": False, "second_opinion": False,
                     "device": "CS-12", "site": 1.0, "strat_fold": 1 + i % 10, "report": "x",
                     "filename_lr": rel.replace("500", "100").replace("hr", "lr"),
                     "filename_hr": rel})
    # a corrupted record: header present, signal file truncated
    (root / "records500/00000/00003_hr.dat").write_bytes(b"\x00\x01")
    pd.DataFrame(rows).to_csv(root / "ptbxl_database.csv", index=False)


def tree_hash(root: Path) -> str:
    h = hashlib.sha256()
    for p in sorted(root.rglob("*")):
        if p.is_file():
            h.update(str(p.relative_to(root)).encode())
            h.update(p.read_bytes())
    return h.hexdigest()


def run_cli(dataset, out, checkpoint, *extra):
    return main(["--dataset", str(dataset), "--output", str(out), "--checkpoint", str(checkpoint),
                 "--batch-size", "4", "--num-workers", "0", "--device", "cpu", *extra])


def test_ptbxl_end_to_end(tmp_path, checkpoint):
    ds, out = tmp_path / "ptbxl", tmp_path / "results"
    ds.mkdir()
    make_ptbxl(ds)
    before = tree_hash(ds)
    assert run_cli(ds, out, checkpoint) == 0
    assert tree_hash(ds) == before, "the original dataset must never be modified"

    for f in ["record_results.csv", "label_discrepancies.csv", "dataset_summary.json",
              "proposed_labels.csv", "label_assessments.csv", "label_statistics.csv",
              "ecgfounder_probabilities.csv.gz", "run_manifest.json", "config_resolved.yaml",
              "run.log", "plots/per_label_agreement.png"]:
        assert (out / f).exists(), f

    rr = pd.read_csv(out / "record_results.csv", dtype={"record_id": str}, keep_default_na=False)
    assert len(rr) == 10 and rr.record_id.is_unique
    for col in ["record_id", "original_labels", "predicted_labels", "prediction_scores",
                "agreement_status", "discrepancy_score", "suggested_additions",
                "suggested_removals", "proposed_labels", "automated_classification"]:
        assert col in rr.columns
    failed = rr[rr.automated_classification == "failed"]
    assert list(failed.record_id) == ["3"]
    assert "load" in failed.failure_reason.iloc[0]
    ok = rr[rr.automated_classification != "failed"]
    db = pd.read_csv(ds / "ptbxl_database.csv")
    for _, r in ok.iterrows():
        codes = set(eval(db.loc[db.ecg_id == int(r.record_id), "scp_codes"].iloc[0]))
        assert set(filter(None, r.original_labels.split(";"))) - codes <= {"AXIS_LAD"}
        json.loads(r.prediction_scores)
    assert "ISC_" in ";".join(ok.not_comparable_labels)  # unsupported, never a mismatch

    disc = pd.read_csv(out / "label_discrepancies.csv")
    assert disc.discrepancy_score.is_monotonic_decreasing
    assert set(disc.automated_classification) <= {"potential_label_issue"}

    s = json.loads((out / "dataset_summary.json").read_text())
    assert s["counts"]["total_recordings_processed"] == 9
    assert s["counts"]["failed_or_incompatible_recordings"] == 1
    for k in ("agreement_rate", "disagreement_rate"):
        assert k in s["record_level"]
    assert "not label accuracy" in s["interpretation"]
    assert s["run"]["checkpoint_sha256"]

    probs = pd.read_csv(out / "ecgfounder_probabilities.csv.gz")
    assert probs.shape == (9, 151)

    # resume: a second run reuses every cached model output
    shards = sorted((out / "cache").rglob("shard_*.npz"))
    assert run_cli(ds, out, checkpoint) == 0
    assert sorted((out / "cache").rglob("shard_*.npz")) == shards
    rr2 = pd.read_csv(out / "record_results.csv", dtype={"record_id": str}, keep_default_na=False)
    pd.testing.assert_frame_equal(rr, rr2)  # deterministic


def test_wfdb_dx_dataset_with_resampling_and_windows(tmp_path, checkpoint):
    ds, out = tmp_path / "challenge", tmp_path / "res"
    (ds / "g1").mkdir(parents=True)
    for i, (dx, secs) in enumerate([("426783006", 10), ("164889003,59118001", 25),
                                    ("164889003", 5)]):
        name = f"A{i:04d}"
        wfdb.wrsamp(name, fs=1000, units=["mV"] * 12, sig_name=LEADS, p_signal=_signal(1000, secs, i),
                    fmt=["16"] * 12, write_dir=str(ds / "g1"),
                    comments=["Age: 50", "Sex: Male", f"Dx: {dx}", "Rx: Unknown"])
    assert run_cli(ds, out, checkpoint) == 0
    rr = pd.read_csv(out / "record_results.csv", keep_default_na=False)
    assert len(rr) == 3
    short = rr[rr.record_id == "g1/A0002"].iloc[0]
    assert short.automated_classification == "failed" and "duration" in short.failure_reason
    long = rr[rr.record_id == "g1/A0001"].iloc[0]
    assert int(float(long.n_windows)) == 2
    assert "resampled_from_1000Hz" in long.signal_warnings


def test_output_inside_dataset_is_refused(tmp_path, checkpoint):
    ds = tmp_path / "ptbxl"
    ds.mkdir()
    make_ptbxl(ds, n=2)
    assert run_cli(ds, ds / "results", checkpoint) == 1


def test_strict_checkpoint_loading(tmp_path):
    sd = build_model(12).state_dict()
    sd.pop("dense.bias")
    p = tmp_path / "bad.pth"
    torch.save({"state_dict": sd}, p)
    with pytest.raises(RuntimeError, match="dense.bias"):
        load_pretrained(p, 12, torch.device("cpu"))
    with pytest.raises(FileNotFoundError, match="huggingface"):
        load_pretrained(tmp_path / "missing.pth", 12, torch.device("cpu"))
